tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT
emit_magen >"$tmp"

case "$mode" in
  stdout) cat "$tmp" ;;
  write)
    mkdir -p "$(dirname -- "$dest")"
    cp "$tmp" "$dest"
    ;;
  check)
    if ! cmp -s "$tmp" "$dest"; then
      echo "magen compose is stale; run lab/scripts/gen-android-ue.sh --target magen --write" >&2
      diff -u "$dest" "$tmp" || true
      exit 1
    fi
    ;;
esac
