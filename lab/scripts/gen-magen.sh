#!/bin/bash
# Emit lab/compose/compose.magen.yml. Called by gen-android-ue.sh --target magen.
# androidN comes from emit_android. This file does not define a second android body.
set -euo pipefail

script_dir=$(CDPATH='' cd -- "$(dirname -- "$0")" && pwd)
root=$(CDPATH='' cd -- "$script_dir/../.." && pwd)

if ! declare -F emit_android >/dev/null 2>&1; then
  export ANDROID_UE_SOURCE_ONLY=1
  # shellcheck source=gen-android-ue.sh
  . "$script_dir/gen-android-ue.sh"
fi

count=${MAGEN_EMIT_COUNT:-2}
mode=${MAGEN_EMIT_MODE:-write}

usage() {
  echo "usage: gen-magen.sh [--check | --stdout | --write] [--count 1|2]" >&2
  exit 2
}

while [ "$#" -gt 0 ]; do
  case "$1" in
    --check) mode="check" ;;
    --stdout) mode="stdout" ;;
    --write) mode="write" ;;
    --count)
      shift
      [ "$#" -gt 0 ] || usage
      count=$1
      ;;
    *) usage ;;
  esac
  shift
done

case "$count" in
  1|2) ;;
  *)
    echo "magen cap is 2 (got ${count})" >&2
    exit 2
    ;;
esac

if [ "$mode" = "check" ] && [ "$count" != 2 ]; then
  echo "--check compares the committed N=2 magen compose" >&2
  exit 2
fi

dest="$root/lab/compose/compose.magen.yml"

emit_ran() {
  local n=$1
  cat <<EOF
  enb${n}:
    profiles: ["epc"]
    image: \${O5G_SRS_IMAGE:?O5G_SRS_IMAGE}
    container_name: o5g-enb${n}
    restart: "no"
    cpus: \${O5G_ENB_CPUS:?O5G_ENB_CPUS}
    mem_limit: \${O5G_ENB_MEM:?O5G_ENB_MEM}
    entrypoint: ["/bin/bash", "/opt/android-ue/android-ue-enb.sh"]
    command:
      - "--rf.device_name=zmq"
      - "--rf.device_args=fail_on_disconnect=true,tx_port0=tcp://*:2000,rx_port0=tcp://\${O5G_UE${n}_UU:?O5G_UE${n}_UU}:2001,tx_port1=tcp://*:2100,rx_port1=tcp://\${O5G_UE${n}_UU}:2101,id=enb,base_srate=\${ZMQ_BASE_SRATE:?ZMQ_BASE_SRATE}"
    environment:
      UE_ADDRESS: \${O5G_UE${n}_UU}
      ANDROID_UE_ZMQ_WAIT: \${ANDROID_UE_ZMQ_WAIT:?ANDROID_UE_ZMQ_WAIT}
      ENB_ID: \${UE${n}_ENB_ID:?UE${n}_ENB_ID}
      MCC: \${MCC:?MCC}
      MNC: \${MNC:?MNC}
      TAC: \${TAC:?TAC}
      N_PRB: \${N_PRB:?N_PRB}
      TX_GAIN: \${TX_GAIN:?TX_GAIN}
      RX_GAIN: \${RX_GAIN:?RX_GAIN}
      MME_ADDR: \${O5G_MME_S1:?O5G_MME_S1}
      GTP_BIND_ADDR: \${O5G_ENB${n}_S1:?O5G_ENB${n}_S1}
      S1C_BIND_ADDR: \${O5G_ENB${n}_S1}
    volumes:
      - ../scripts/android-ue-enb.sh:/opt/android-ue/android-ue-enb.sh:ro
    networks:
      s1:
        ipv4_address: \${O5G_ENB${n}_S1}
      uu:
        ipv4_address: \${O5G_ENB${n}_UU:?O5G_ENB${n}_UU}
    depends_on:
      ue${n}:
        condition: service_started

  ue${n}:
    profiles: ["epc"]
    image: \${O5G_SRS_IMAGE}
    container_name: o5g-ue${n}
    restart: "no"
    cpus: \${O5G_UE_CPUS:?O5G_UE_CPUS}
    mem_limit: \${O5G_UE_MEM:?O5G_UE_MEM}
    cap_add: [NET_ADMIN]
    devices:
      - "/dev/net/tun:/dev/net/tun"
    sysctls:
      net.ipv6.conf.default.disable_ipv6: "1"
      net.ipv6.conf.eth0.disable_ipv6: "1"
    command:
      - ue
      - "--rf.device_name=zmq"
      - "--rf.device_args=tx_port0=tcp://\${O5G_UE${n}_UU}:2001,rx_port0=tcp://\${O5G_ENB${n}_UU}:2000,tx_port1=tcp://\${O5G_UE${n}_UU}:2101,rx_port1=tcp://\${O5G_ENB${n}_UU}:2100,id=ue,base_srate=\${ZMQ_BASE_SRATE}"
    environment:
      UE_IMSI: \${UE${n}_IMSI:?UE${n}_IMSI}
      UE_KI: \${UE${n}_KI:?UE${n}_KI}
      UE_OPC: \${UE${n}_OPC:?UE${n}_OPC}
      UE_IMEI: \${UE${n}_IMEI:?UE${n}_IMEI}
      UE_ALGO: \${UE_ALGO:?UE_ALGO}
      UE_ADDRESS: \${O5G_UE${n}_UU}
      ENB_ADDRESS: \${O5G_ENB${n}_UU}
    volumes:
      - ../config/ran/android-ue.conf.template:/etc/srsran/ue.conf:ro
    networks:
      uu:
        ipv4_address: \${O5G_UE${n}_UU}

EOF
}

